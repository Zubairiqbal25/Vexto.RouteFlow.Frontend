/**
 * Outlines the "Vexto" wordmark from Inter SemiBold into `wordmark.generated.mjs`.
 *
 * Run once, by hand, and commit the result — which is why neither `opentype.js` nor the font file
 * is a workspace dependency:
 *
 *   npm i --no-save opentype.js
 *   curl -Lo /tmp/Inter-SemiBold.woff \
 *     https://cdn.jsdelivr.net/npm/@fontsource/inter@4.5.15/files/inter-all-600-normal.woff
 *   node tools/brand/extract-wordmark.mjs /tmp/Inter-SemiBold.woff
 *
 * The wordmark is outlined rather than left as `<text>` because a `<text>` logo silently becomes a
 * different logo on any machine without Inter — an email client, a PDF, a design tool. Inter is
 * OFL-licensed, which permits this.
 *
 * Glyphs are positioned by advance width plus kerning rather than through `font.getPath`, which
 * trips over a GSUB lookup format opentype.js does not implement.
 */
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';

const fontPath = process.argv[2];

if (!fontPath) {
  console.error('usage: node tools/brand/extract-wordmark.mjs <path-to-Inter-SemiBold.woff>');
  process.exit(1);
}

const TEXT = 'Vexto';

const buffer = fs.readFileSync(fontPath);
const font = opentype.parse(
  buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength),
);

// Normalise to a cap height of exactly 100 units, so the lockup can size the wordmark by cap
// height — the only measurement that optically matches a geometric mark.
const capHeight = font.tables.os2.sCapHeight;
const size = (100 * font.unitsPerEm) / capHeight;
const scale = size / font.unitsPerEm;

const glyphs = [...TEXT].map((character) => font.charToGlyph(character));
const outline = new opentype.Path();
let pen = 0;

glyphs.forEach((glyph, index) => {
  outline.commands.push(...glyph.getPath(pen, 0, size).commands);
  pen += glyph.advanceWidth * scale;

  const next = glyphs[index + 1];
  if (next) {
    pen += font.getKerningValue(glyph, next) * scale;
  }
});

const box = outline.getBoundingBox();
const round = (value) => Number(value.toFixed(2));

const module = `/**
 * The "Vexto" wordmark, outlined from Inter SemiBold — generated by \`extract-wordmark.mjs\`.
 * Do not edit by hand.
 *
 * Normalised so the cap height is exactly 100 units and the baseline is y = 0. Cap tops are
 * therefore at y = -100, and \`box.y2\` is the round-glyph overshoot below the baseline.
 */
export const WORDMARK = {
  text: ${JSON.stringify(TEXT)},
  source: 'Inter SemiBold (OFL)',
  capHeight: 100,
  /** Inter's cap height as a share of its font size — how a CSS font-size maps to cap height. */
  capRatio: ${round(capHeight / font.unitsPerEm)},
  box: {
    x1: ${round(box.x1)},
    y1: ${round(box.y1)},
    x2: ${round(box.x2)},
    y2: ${round(box.y2)},
  },
  path: '${outline.toPathData(2)}',
};
`;

const out = path.join(import.meta.dirname, 'wordmark.generated.mjs');
fs.writeFileSync(out, module);
console.log(`wrote ${out}`);
console.log(`  ink ${round(box.x2 - box.x1)} x ${round(box.y2 - box.y1)} at cap height 100`);
